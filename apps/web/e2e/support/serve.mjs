// The browser-test topology (B11 design D-E2E-2): a TLS edge on https://localhost:<port> that routes /api/v1/* to the api
// (KAURO_E2E_API_ORIGIN, when a suite starts one) and every other path to the standalone Next.js server — the local stand-in of the production
// load balancer's URL map (reference UI_STATE_AND_COPY_CONTRACT "Origins and navigation": browser API traffic uses the same
// origin's /api/v1). TLS is not optional: WebKit refuses a Secure (__Host-) cookie over http://localhost, measured on
// 2026-09-29 with Playwright 1.63.0 (WebKit 26.6). The certificate is a fresh self-signed P-256 certificate for localhost,
// generated by openssl for this run in a temporary directory and removed on exit; nothing is trusted system-wide.
import { execFileSync, spawn } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import http from "node:http";
import https from "node:https";
import { tmpdir } from "node:os";
import { join } from "node:path";

const edgePort = Number(process.env.KAURO_E2E_PORT ?? 44300);
const nextPort = edgePort + 1;
const apiOrigin = process.env.KAURO_E2E_API_ORIGIN ? new URL(process.env.KAURO_E2E_API_ORIGIN) : null;

const tls = mkdtempSync(join(tmpdir(), "kauro-e2e-tls-"));
const cleanup = () => rmSync(tls, { recursive: true, force: true });
execFileSync(
  "openssl",
  ["req", "-x509", "-newkey", "ec", "-pkeyopt", "ec_paramgen_curve:P-256", "-nodes", "-days", "1", "-subj", "/CN=localhost", "-addext", "subjectAltName=DNS:localhost", "-keyout", join(tls, "key.pem"), "-out", join(tls, "cert.pem")],
  { stdio: "ignore" },
);

// the deployable standalone server of `pnpm run build` (scripts/next.mjs), exactly what the container runs
const server = join(import.meta.dirname, "..", "..", ".next", "standalone", "apps", "web", "server.js");
if (!existsSync(server)) {
  cleanup();
  throw new Error(`no standalone server at ${server}: run pnpm run build first`);
}
const next = spawn(process.execPath, [server], {
  stdio: "inherit",
  env: { ...process.env, NEXT_TELEMETRY_DISABLED: "1", NODE_ENV: "production", PORT: String(nextPort), HOSTNAME: "127.0.0.1" },
});

const edge = https.createServer({ key: readFileSync(join(tls, "key.pem")), cert: readFileSync(join(tls, "cert.pem")) }, (req, res) => {
  const toApi = apiOrigin !== null && (req.url === "/api/v1" || req.url?.startsWith("/api/v1/"));
  const target = toApi ? { hostname: apiOrigin.hostname, port: apiOrigin.port } : { hostname: "127.0.0.1", port: nextPort };
  const upstream = http.request(
    { ...target, method: req.method, path: req.url, headers: { ...req.headers, "x-forwarded-proto": "https", "x-forwarded-host": req.headers.host ?? `localhost:${edgePort}` } },
    (answer) => {
      res.writeHead(answer.statusCode ?? 502, answer.rawHeaders);
      answer.pipe(res);
    },
  );
  upstream.on("error", () => {
    if (!res.headersSent) res.writeHead(502, { "content-type": "text/plain", "cache-control": "no-store" });
    res.end("edge: upstream unavailable\n");
  });
  req.pipe(upstream);
});
edge.listen(edgePort, "localhost");

const stop = () => {
  edge.close();
  next.kill();
  cleanup();
  process.exit(0);
};
process.on("SIGINT", stop);
process.on("SIGTERM", stop);
next.on("exit", (code) => {
  edge.close();
  cleanup();
  process.exit(code ?? 1);
});
