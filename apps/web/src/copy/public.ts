export type PublicCopyId = keyof typeof PUBLIC_COPY;
export type CopyValues = Readonly<Record<string, string | number>>;

const PLACEHOLDER = /\{([A-Za-z][A-Za-z0-9]*)\}/g;

/** The placeholder names a message carries, in order of first use. */
export function placeholdersOf(text: string): readonly string[] {
  return [...new Set([...text.matchAll(PLACEHOLDER)].map((match) => match[1] ?? ""))];
}

/**
 * A message with its placeholders filled. A message asked for with a placeholder unfilled, or with a value it has no place for, is a
 * programming error and throws: a page never shows "{price}" to a visitor and never drops a figure it was given.
 */
export function copy(id: PublicCopyId, values: CopyValues = {}): string {
  const text: string = PUBLIC_COPY[id];
  const names = placeholdersOf(text);
  for (const name of names) if (!(name in values)) throw new Error(`COPY_PLACEHOLDER_MISSING ${id} ${name}`);
  for (const name of Object.keys(values)) if (!names.includes(name)) throw new Error(`COPY_VALUE_UNUSED ${id} ${name}`);
  return text.replaceAll(PLACEHOLDER, (_, name: string) => String(values[name]));
}
