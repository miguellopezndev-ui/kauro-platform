// Every runtime role's read/write boundary as one reviewed matrix (B06 program work "every role's read/write boundary";
// re-check finding N11: spot probes are not a boundary review). The test reads, from the catalog of a freshly migrated cluster,
// every table privilege and column privilege the five runtime groups hold in the kauro schemas and every row-security policy,
// and compares them with the committed matrix test/fixtures/runtime-boundary.json. A migration that widens or narrows any
// role's privileges, or changes a policy, fails here until the matrix is changed in the same review (21 "Golden files are useful
// only when their origin and review are known"; the file is written by hand from this output, never regenerated by a test).
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { after, before, test } from "node:test";
import { fileURLToPath } from "node:url";
import { startTemporaryPostgres, type TemporaryPostgres } from "../src/testing/index.js";
import { readBoundary, type RuntimeBoundary } from "./boundary.js";

let pg: TemporaryPostgres;
before(async () => {
  pg = await startTemporaryPostgres();
});
after(async () => {
  await pg.stop();
});

const here = dirname(fileURLToPath(import.meta.url));
/** The committed matrix lives beside the test sources (dist/test → ../../test/fixtures). */
const MATRIX = join(here, "..", "..", "test", "fixtures", "runtime-boundary.json");

test("N11/B06 work: every runtime role's table and column privileges and every row-security policy equal the reviewed matrix", async () => {
  const actual = await readBoundary(pg);
  const expected = JSON.parse(readFileSync(MATRIX, "utf8")) as RuntimeBoundary;
  assert.deepEqual(actual.tables, expected.tables, "table privileges of the runtime roles");
  assert.deepEqual(actual.columns, expected.columns, "column privileges of the runtime roles");
  assert.deepEqual(actual.policies, expected.policies, "row-security policies");
  // the matrix states what the design promises: the request handlers never DELETE, and never write security status, the
  // inbox, step-up proofs or validation receipts (D-RLS-2, N1, N2, D-EVID-1)
  const app = expected.tables["kauro_app"] ?? {};
  for (const [rel, privileges] of Object.entries(app)) assert.equal(privileges.includes("DELETE"), false, `kauro_app DELETE on ${rel}`);
  assert.deepEqual(app["kauro.identities"], ["SELECT"]);
  assert.equal(app["kauro.inbox_records"], undefined);
  assert.deepEqual(app["kauro.assurance_proofs"], ["SELECT"]);
  assert.deepEqual(app["kauro.validation_receipts"], ["SELECT"]);
  assert.equal((expected.columns["kauro_app"]?.["kauro.identities"]?.["UPDATE"] ?? []).includes("state"), false);
  for (const role of ["kauro_assurance", "kauro_validator", "kauro_ingress"]) {
    for (const [rel, privileges] of Object.entries(expected.tables[role] ?? {})) {
      // B11 D-AUTH-1: the authentication boundary also keeps the web sessions — it reads them (a row only when the transaction
      // presents its secret hash: web_sessions_presented) and updates named columns only; nothing else is read or rewritten
      if (role === "kauro_assurance" && rel === "kauro.web_sessions") {
        assert.deepEqual(privileges, ["INSERT", "SELECT"]);
        continue;
      }
      assert.equal(privileges.includes("SELECT") || privileges.includes("UPDATE") || privileges.includes("DELETE"), false, `${role} reads or rewrites a whole table`);
    }
  }
  // the web sessions belong to the authentication boundary; the request handlers hold only the lock-only path of 0047 on the session their
  // own transaction presents (B11 D-AUTH-1 as amended, PV1R-07 r4): column SELECT of the judged columns, UPDATE of the immutable session_id,
  // an UPDATE policy whose WITH CHECK is false, no table privilege
  assert.equal(expected.tables["kauro_app"]?.["kauro.web_sessions"], undefined, "kauro_app table privilege on web_sessions");
  assert.deepEqual(expected.columns["kauro_app"]?.["kauro.web_sessions"], {
    SELECT: ["absolute_expires_at", "idle_expires_at", "revoked_at", "secret_sha256", "user_id"],
    UPDATE: ["session_id"],
  });
  assert.equal(expected.policies["web_sessions/web_sessions_request_lock"]?.check, "false");
  assert.deepEqual(expected.policies["web_sessions/web_sessions_request_lock"]?.roles, ["kauro_app"]);
  assert.deepEqual(expected.policies["web_sessions/web_sessions_request_read"]?.roles, ["kauro_app"]);
  for (const role of ["kauro_control", "kauro_validator", "kauro_ingress"]) {
    assert.equal(expected.tables[role]?.["kauro.web_sessions"], undefined, `${role} on web_sessions`);
    assert.equal(expected.columns[role]?.["kauro.web_sessions"], undefined, `${role} columns of web_sessions`);
  }
  assert.deepEqual(Object.keys(expected.columns["kauro_assurance"]?.["kauro.web_sessions"] ?? {}), ["UPDATE"]);
  assert.equal((expected.columns["kauro_assurance"]?.["kauro.web_sessions"]?.["UPDATE"] ?? []).some((c) => ["user_id", "secret_sha256", "session_id", "absolute_expires_at", "created_at"].includes(c)), false, "what a session is never changes");
});
