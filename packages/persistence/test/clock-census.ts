// The clock census of B05 D5-20 (CK1, CK2; docs/design/B05-cores.md D5-20 "one clock by source", D5-11 deferred census): read from the
// live kauro schema of a cluster (one read-only session; the catalogs carry no RLS; no row lock) and from the migration files.
//
//   Sources (P): every clock primitive (pg_proc's clock functions read by name, the SQL value functions, the 'now'/'today'/'tomorrow'/
//     'yesterday' literals cast to a temporal type) outside the bodies of kauro.server_now() and kauro.effect_now(), in function
//     bodies, RLS policies, CHECK constraints, views, trigger WHEN clauses and column defaults, and in every migration file.
//   Stamps (S): a column receiving an instant: NEW.col := an instant, SET col = an instant, INSERT ... VALUES with an instant, a column
//     DEFAULT, and kauro.require_server_instant's argument.
//   Judges (J): every <, <=, >, >= one of whose operands is a clock call, a clock-tainted or temporal variable, a temporal parameter or
//     a column declared timestamptz, timestamp or date anywhere in kauro (name-global).
//   Dynamic (D): every plpgsql EXECUTE of a string.
// Each site is keyed by its object and its ordinal among the sites of its kind in that object, with its normalized text, so a changed
// body changes its rows (the census is regenerated by write mode, never hand-merged). What it cannot see is stated in D5-20: an instant
// carried through an untyped value and compared elsewhere, and the text of dynamic SQL.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import type { Client } from "pg";

export type SiteKind = "P" | "S" | "J" | "D";
export type ObjectKind = "function" | "policy" | "check" | "view" | "trigger_when" | "default" | "trigger_arg" | "file";

export interface Site {
  /** `${objectKind}:${object}#${kind}${ordinal}` */
  readonly key: string;
  readonly kind: SiteKind;
  readonly objectKind: ObjectKind;
  readonly object: string;
  readonly ordinal: number;
  /** The site's text, whitespace-normalized (a judge: its two operands and operator; a stamp: the column and its value). */
  readonly text: string;
  /** file:line of the live definition (a function: the site's own line; another object: its definition's first line). */
  readonly at: string;
  /** Judges: whether an operand is a clock call or clock-tainted variable ("now"), a temporal parameter, or stored instants only. */
  readonly operands?: "NOW" | "PARAM" | "STORED";
  /** Stamps: the stamped column (table.column when the table is known). */
  readonly column?: string;
}

const PRIMITIVE_CALL = /(?<![\w.])(?:pg_catalog\.)?(now|transaction_timestamp|statement_timestamp|clock_timestamp|timeofday|pg_xact_commit_timestamp|pg_last_xact_replay_timestamp|pg_postmaster_start_time|pg_conf_load_time|pg_stat_get_snapshot_timestamp)\s*\(/gi;
const VALUE_FUNCTION = /(?<![\w.'"])(current_date|current_timestamp|current_time|localtimestamp|localtime)(?![\w'"])/gi;
const TEMPORAL_TYPE = "(?:timestamptz|timestamp(?:\\s*\\(\\d\\))?(?:\\s+with(?:out)?\\s+time\\s+zone)?|date|time(?:tz)?)";
const LITERAL = new RegExp(`'(now|today|tomorrow|yesterday)'\\s*::\\s*${TEMPORAL_TYPE}|\\b${TEMPORAL_TYPE}\\s+'(now|today|tomorrow|yesterday)'`, "gi");
const SANCTIONED_CLOCK = /\bkauro\.(server_now|effect_now)\s*\(\s*\)/i;
const SANCTIONED_FUNCTIONS = new Set(["server_now", "effect_now"]);

/** Comments replaced by spaces (positions kept). */
export function stripComments(sql: string): string {
  let out = "";
  let i = 0;
  while (i < sql.length) {
    if (sql[i] === "'") {
      const j = endOfString(sql, i);
      out += sql.slice(i, j);
      i = j;
    } else if (sql.startsWith("--", i)) {
      const j = sql.indexOf("\n", i);
      const end = j === -1 ? sql.length : j;
      out += " ".repeat(end - i);
      i = end;
    } else if (sql.startsWith("/*", i)) {
      const j = sql.indexOf("*/", i + 2);
      const end = j === -1 ? sql.length : j + 2;
      out += sql.slice(i, end).replace(/[^\n]/g, " ");
      i = end;
    } else {
      out += sql[i];
      i += 1;
    }
  }
  return out;
}

function endOfString(sql: string, i: number): number {
  let j = i + 1;
  while (j < sql.length) {
    if (sql[j] === "'") {
      if (sql[j + 1] === "'") j += 2;
      else return j + 1;
    } else j += 1;
  }
  return j;
}

/** String literal contents replaced by spaces (the quotes kept), so an operator or a clock word in a message is not a site. */
export function maskStrings(sql: string): string {
  let out = "";
  let i = 0;
  while (i < sql.length) {
    if (sql[i] === "'") {
      const j = endOfString(sql, i);
      out += "'" + " ".repeat(Math.max(0, j - i - 2)) + (j - i >= 2 ? "'" : "");
      i = j;
    } else {
      out += sql[i];
      i += 1;
    }
  }
  return out;
}

const norm = (s: string): string => s.replace(/\s+/g, " ").trim();

/** The primitives of a text (comments stripped), in order, with their offsets. */
export function primitivesOf(text: string): Array<{ index: number; text: string }> {
  const src = stripComments(text);
  const masked = maskStrings(src);
  const found: Array<{ index: number; text: string }> = [];
  for (const m of masked.matchAll(PRIMITIVE_CALL)) found.push({ index: m.index!, text: m[0].replace(/\s*\($/, "()") });
  for (const m of masked.matchAll(VALUE_FUNCTION)) found.push({ index: m.index!, text: m[0] });
  for (const m of masked.matchAll(/(?<![\w.])age\s*\(/gi)) {
    const close = closingParen(masked, m.index! + m[0].length - 1);
    if (close !== -1 && !topLevelComma(masked.slice(m.index! + m[0].length, close))) found.push({ index: m.index!, text: "age(<one argument>)" });
  }
  for (const m of src.matchAll(LITERAL)) found.push({ index: m.index!, text: norm(m[0]) });
  return found.sort((a, b) => a.index - b.index);
}

function closingParen(s: string, open: number): number {
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === "(") depth += 1;
    else if (s[i] === ")") {
      depth -= 1;
      if (depth === 0) return i;
    }
  }
  return -1;
}

function topLevelComma(s: string): boolean {
  let depth = 0;
  for (const ch of s) {
    if (ch === "(") depth += 1;
    else if (ch === ")") depth -= 1;
    else if (ch === "," && depth === 0) return true;
  }
  return false;
}

const BOUNDARY_WORDS = new Set(["and", "or", "not", "if", "elsif", "when", "where", "then", "else", "case", "on", "return", "select", "while", "until", "having", "end", "loop", "into", "from", "order", "group", "limit", "returning", "for", "set", "is", "in", "between", "using", "check", "exists", "values", "raise", "perform", "assert"]);

/** The operand left of `at` (an operator's offset): back to a delimiter at depth 0. */
function leftOperand(s: string, at: number): string {
  let depth = 0;
  let i = at - 1;
  for (; i >= 0; i--) {
    const ch = s[i]!;
    if (ch === ")") depth += 1;
    else if (ch === "(") {
      if (depth === 0) break;
      depth -= 1;
    } else if (depth === 0 && (ch === "," || ch === ";" || ch === "=" || ch === "<" || ch === ">" || ch === "!")) break;
    else if (depth === 0 && /\s/.test(ch)) {
      const word = /([A-Za-z_]+)$/.exec(s.slice(Math.max(0, i - 12), i))?.[1]?.toLowerCase();
      if (word !== undefined && BOUNDARY_WORDS.has(word) && !/[\w.]/.test(s[i - word.length - 1] ?? " ")) break;
    }
  }
  return s.slice(i + 1, at);
}

/** The operand right of `from` (just after an operator): forward to a delimiter at depth 0. */
function rightOperand(s: string, from: number): string {
  let depth = 0;
  let i = from;
  for (; i < s.length; i++) {
    const ch = s[i]!;
    if (ch === "(") depth += 1;
    else if (ch === ")") {
      if (depth === 0) break;
      depth -= 1;
    } else if (depth === 0 && (ch === "," || ch === ";" || ch === "=" || ch === "<" || ch === ">" || ch === "!")) break;
    else if (depth === 0 && /\s/.test(ch)) {
      const word = /^([A-Za-z_]+)/.exec(s.slice(i + 1, i + 14))?.[1]?.toLowerCase();
      if (word !== undefined && BOUNDARY_WORDS.has(word) && !/[\w.]/.test(s[i + 1 + word.length] ?? " ")) break;
    }
  }
  return s.slice(from, i);
}

export interface Vocabulary {
  /** Column names declared timestamptz, timestamp or date anywhere in kauro (name-global). */
  readonly temporalColumns: ReadonlySet<string>;
}

interface Scope {
  readonly params: ReadonlySet<string>;
  /** Declared temporal variables and variables assigned from a clock (clock-tainted). */
  readonly temporalVars: ReadonlySet<string>;
  readonly taintedVars: ReadonlySet<string>;
}

const NO_SCOPE: Scope = { params: new Set(), temporalVars: new Set(), taintedVars: new Set() };

function hasClock(expr: string, scope: Scope): boolean {
  if (SANCTIONED_CLOCK.test(expr) || primitivesOf(expr).length > 0) return true;
  for (const id of identifiers(expr)) if (!id.includes(".") && scope.taintedVars.has(id)) return true;
  return false;
}

function identifiers(expr: string): string[] {
  return [...expr.matchAll(/(?<![\w'])([A-Za-z_][\w]*(?:\.[A-Za-z_][\w]*)*)(?![\w(])/g)].map((m) => m[1]!.toLowerCase());
}

/** Classifies an operand: NOW (a clock or tainted variable), PARAM (a temporal parameter), STORED (a temporal column), or null. */
function operandClass(expr: string, scope: Scope, vocab: Vocabulary): "NOW" | "PARAM" | "STORED" | null {
  if (hasClock(expr, scope)) return "NOW";
  const ids = identifiers(expr);
  if (ids.some((id) => !id.includes(".") && scope.params.has(id))) return "PARAM";
  if (ids.some((id) => !id.includes(".") && scope.temporalVars.has(id))) return "NOW";
  if (ids.some((id) => vocab.temporalColumns.has(id.split(".").pop()!))) return "STORED";
  if (/\$\d/.test(expr) && /::\s*(timestamptz|timestamp|date)\b/i.test(expr)) return "PARAM";
  return null;
}

const RANK = { NOW: 3, PARAM: 2, STORED: 1 } as const;

/** The judges of a text: comparisons with a temporal operand, in order. */
export function judgesOf(text: string, vocab: Vocabulary, scope: Scope = NO_SCOPE): Array<{ index: number; text: string; operands: "NOW" | "PARAM" | "STORED" }> {
  const s = maskStrings(stripComments(text));
  const out: Array<{ index: number; text: string; operands: "NOW" | "PARAM" | "STORED" }> = [];
  for (const m of s.matchAll(/(<=|>=|<(?![>=<@])|>(?![>=]))/g)) {
    const i = m.index!;
    const prev = s[i - 1] ?? " ";
    if (prev === "<" || prev === ">" || prev === "-" || prev === "=" || prev === "@" || prev === "#" || prev === "!" || prev === "|" || prev === "&") continue;
    const op = m[0];
    const left = leftOperand(s, i);
    const right = rightOperand(s, i + op.length);
    const classes = [operandClass(left, scope, vocab), operandClass(right, scope, vocab)].filter((c): c is "NOW" | "PARAM" | "STORED" => c !== null);
    if (classes.length === 0) continue;
    const operands = classes.reduce((a, b) => (RANK[a] >= RANK[b] ? a : b));
    out.push({ index: i, text: norm(`${left} ${op} ${right}`), operands });
  }
  return out;
}

const ASSIGNMENT_KEYWORDS = new Set(["declare", "begin", "then", "else", "loop", "constant"]);

/** plpgsql scope of a function: temporal parameters, declared temporal variables and clock-tainted variables. */
function scopeOf(body: string, params: ReadonlyArray<{ name: string; temporal: boolean }>): Scope {
  const src = maskStrings(stripComments(body));
  const temporalVars = new Set<string>();
  const taintedVars = new Set<string>();
  for (const m of src.matchAll(/(?:^|[\s;(,])([a-z_][\w]*)\s+(?:constant\s+)?(timestamptz|timestamp|date)\b/gi)) temporalVars.add(m[1]!.toLowerCase());
  // assignments from a clock, repeated to a fixed point (a variable assigned from a tainted one is tainted)
  for (let pass = 0; pass < 3; pass++) {
    for (const m of src.matchAll(/(?:^|[\s;])([a-z_][\w]*)[ 	]*(?:[a-z_ 	]*?)?:=\s*([^;]+);/gi)) {
      const name = m[1]!.toLowerCase();
      if (name === "new" || name === "old" || ASSIGNMENT_KEYWORDS.has(name)) continue;
      if (hasClock(m[2]!, { params: new Set(), temporalVars, taintedVars })) taintedVars.add(name);
    }
  }
  const p = new Set(params.filter((x) => x.temporal).map((x) => x.name.toLowerCase()));
  for (const v of p) temporalVars.delete(v);
  return { params: p, temporalVars, taintedVars };
}

/** The stamps of a function body: NEW.col := instant, SET col = instant, INSERT INTO t (cols) VALUES (... instant ...). */
function stampsOf(body: string, scope: Scope): Array<{ index: number; text: string; column: string }> {
  const src = maskStrings(stripComments(body));
  const out: Array<{ index: number; text: string; column: string }> = [];
  for (const m of src.matchAll(/\bNEW\.([a-z_][\w]*)\s*:=\s*([^;]+);/gi)) if (hasClock(m[2]!, scope)) out.push({ index: m.index!, text: norm(`NEW.${m[1]} := ${m[2]}`), column: m[1]!.toLowerCase() });
  for (const m of src.matchAll(/\bUPDATE\s+kauro\.([a-z_][\w]*)(?:\s+(?:AS\s+)?[a-z_]\w*)?\s+SET\s+/gi)) {
    const start = m.index! + m[0].length;
    const tail = src.slice(start);
    const stop = /\b(WHERE|RETURNING|FROM)\b|;/i.exec(tail);
    const setList = tail.slice(0, stop?.index ?? tail.length);
    let offset = 0;
    for (const part of splitTop(setList)) {
      const a = /^\s*([a-z_][\w]*)\s*=\s*([\s\S]+)$/i.exec(part);
      if (a && hasClock(a[2]!, scope)) out.push({ index: start + offset, text: norm(`${m[1]}.${a[1]} = ${a[2]}`), column: `${m[1]}.${a[1]!.toLowerCase()}` });
      offset += part.length + 1;
    }
  }
  for (const m of src.matchAll(/\bINSERT\s+INTO\s+kauro\.([a-z_][\w]*)\s*\(([^)]*)\)\s*VALUES\s*\(/gi)) {
    const open = m.index! + m[0].length - 1;
    const close = closingParen(src, open);
    if (close === -1) continue;
    const cols = m[2]!.split(",").map((c) => c.trim().toLowerCase());
    splitTop(src.slice(open + 1, close)).forEach((v, k) => {
      if (hasClock(v, scope) && cols[k] !== undefined) out.push({ index: m.index!, text: norm(`${m[1]}.${cols[k]} VALUES ${v}`), column: `${m[1]}.${cols[k]}` });
    });
  }
  return out.sort((a, b) => a.index - b.index);
}

function splitTop(s: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let cur = "";
  for (const ch of s) {
    if (ch === "(") depth += 1;
    else if (ch === ")") depth -= 1;
    if (ch === "," && depth === 0) {
      parts.push(cur);
      cur = "";
    } else cur += ch;
  }
  if (cur.trim() !== "") parts.push(cur);
  return parts;
}

// --- migration files: where each live object is defined ---------------------------------------------------------------------------

interface FileIndex {
  /** function name -> its latest CREATE [OR REPLACE] FUNCTION: file, line of the body's first character and the raw body. */
  readonly functions: Map<string, { file: string; bodyLine: number; body: string }>;
  /** `${kind}:${name}` -> file:line of the latest definition (policies, constraints, views, triggers, table columns). */
  readonly objects: Map<string, string>;
  readonly files: ReadonlyArray<{ file: string; raw: string }>;
}

const lineAt = (raw: string, index: number): number => raw.slice(0, index).split("\n").length;

export function indexMigrations(dir: string): FileIndex {
  const files = readdirSync(dir).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort().map((file) => ({ file, raw: readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n") }));
  const functions = new Map<string, { file: string; bodyLine: number; body: string }>();
  const objects = new Map<string, string>();
  for (const { file, raw } of files) {
    const src = stripComments(raw);
    const tag = file.slice(0, 4);
    for (const m of src.matchAll(/CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+kauro\.(\w+)\s*\([\s\S]*?\bAS\s+(\$\w*\$)/gi)) {
      const open = m.index! + m[0].length;
      const close = raw.indexOf(m[2]!, open);
      if (close === -1) continue;
      functions.set(m[1]!.toLowerCase(), { file: tag, bodyLine: lineAt(raw, open), body: raw.slice(open, close) });
    }
    for (const m of src.matchAll(/CREATE\s+POLICY\s+(\w+)\s+ON\s+kauro\.(\w+)/gi)) objects.set(`policy:${m[2]}.${m[1]}`, `${tag}:${lineAt(raw, m.index!)}`);
    for (const m of src.matchAll(/CREATE\s+(?:OR\s+REPLACE\s+)?VIEW\s+kauro\.(\w+)/gi)) objects.set(`view:${m[1]}`, `${tag}:${lineAt(raw, m.index!)}`);
    for (const m of src.matchAll(/CREATE\s+(?:CONSTRAINT\s+)?TRIGGER\s+(\w+)[\s\S]*?\bON\s+kauro\.(\w+)/gi)) objects.set(`trigger:${m[2]}.${m[1]}`, `${tag}:${lineAt(raw, m.index!)}`);
    for (const m of src.matchAll(/CONSTRAINT\s+(\w+)\s+CHECK\b/gi)) objects.set(`check:${m[1]}`, `${tag}:${lineAt(raw, m.index!)}`);
    for (const t of src.matchAll(/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?kauro\.(\w+)\s*\(/gi)) {
      const close = closingParen(src, t.index! + t[0].length - 1);
      const bodyStart = t.index! + t[0].length;
      for (const c of src.slice(bodyStart, close).matchAll(/(?:^|\n)\s+([a-z_]\w*)\s+[a-z]/g)) {
        objects.set(`column:${t[1]}.${c[1]}`, `${tag}:${lineAt(raw, bodyStart + c.index! + 1)}`);
      }
    }
    for (const m of src.matchAll(/ALTER\s+TABLE\s+(?:ONLY\s+)?kauro\.(\w+)\s+(?:ADD\s+COLUMN\s+(?:IF\s+NOT\s+EXISTS\s+)?|ALTER\s+COLUMN\s+)([a-z_]\w*)/gi)) objects.set(`column:${m[1]}.${m[2]}`, `${tag}:${lineAt(raw, m.index!)}`);
    for (const m of src.matchAll(/ADD\s+CONSTRAINT\s+(\w+)\s+CHECK\b/gi)) objects.set(`check:${m[1]}`, `${tag}:${lineAt(raw, m.index!)}`);
  }
  return { functions, objects, files };
}

// --- the census --------------------------------------------------------------------------------------------------------------------

export interface Census {
  readonly sites: ReadonlyArray<Site>;
  readonly deferredTriggers: ReadonlyArray<{ table: string; trigger: string; fn: string; body: string }>;
  readonly deferredForeignKeys: ReadonlyArray<{ name: string; table: string; references: string }>;
}

/** The census of the live schema on `c` (read-only) and of the migration files in `dir`. */
export async function census(c: Client, dir: string): Promise<Census> {
  const index = indexMigrations(dir);
  const temporalColumns = new Set(
    (await c.query<{ n: string }>(
      `SELECT DISTINCT a.attname AS n FROM pg_attribute a JOIN pg_class r ON r.oid = a.attrelid JOIN pg_namespace s ON s.oid = r.relnamespace
        WHERE s.nspname = 'kauro' AND a.attnum > 0 AND NOT a.attisdropped AND a.atttypid IN ('timestamptz'::regtype, 'timestamp'::regtype, 'date'::regtype)`,
    )).rows.map((r) => r.n),
  );
  const vocab: Vocabulary = { temporalColumns };
  const sites: Site[] = [];
  const counters = new Map<string, number>();
  const push = (objectKind: ObjectKind, object: string, kind: SiteKind, text: string, at: string, extra: { operands?: Site["operands"]; column?: string } = {}) => {
    const base = `${objectKind}:${object}`;
    const n = (counters.get(`${base}#${kind}`) ?? 0) + 1;
    counters.set(`${base}#${kind}`, n);
    sites.push({ key: `${base}#${kind}${n}`, kind, objectKind, object, ordinal: n, text, at, ...(extra.operands === undefined ? {} : { operands: extra.operands }), ...(extra.column === undefined ? {} : { column: extra.column }) });
  };

  // functions (plpgsql and sql bodies)
  const fns = (await c.query<{ name: string; src: string; lang: string; args: string[] | null; modes: string[] | null; types: string[] | null }>(
    `SELECT p.proname AS name, p.prosrc AS src, l.lanname AS lang, p.proargnames AS args, p.proargmodes::text[] AS modes,
            ARRAY(SELECT format_type(t, NULL) FROM unnest(p.proargtypes) AS t) AS types
       FROM pg_proc p JOIN pg_namespace s ON s.oid = p.pronamespace JOIN pg_language l ON l.oid = p.prolang
      WHERE s.nspname = 'kauro' AND p.prokind = 'f' ORDER BY p.proname, p.oid`,
  )).rows;
  for (const f of fns) {
    if (SANCTIONED_FUNCTIONS.has(f.name)) continue;
    const body = f.src.replace(/\r\n/g, "\n");
    const params = (f.args ?? []).map((name, k) => ({ name, temporal: /^(timestamp|date|time)/.test(f.types?.[k] ?? "") }));
    const scope = f.lang === "plpgsql" || f.lang === "sql" ? scopeOf(body, params) : NO_SCOPE;
    const def = index.functions.get(f.name);
    const at = (offset: number): string => (def === undefined ? "live-only" : `${def.file}:${def.bodyLine + lineAt(body, offset) - 1}`);
    for (const p of primitivesOf(body)) push("function", f.name, "P", p.text, at(p.index));
    for (const s of stampsOf(body, scope)) push("function", f.name, "S", s.text, at(s.index), { column: s.column });
    for (const j of judgesOf(body, vocab, scope)) push("function", f.name, "J", j.text, at(j.index), { operands: j.operands });
    if (f.lang === "plpgsql") for (const m of maskStrings(stripComments(body)).matchAll(/\bEXECUTE\s+(?!FUNCTION\b|PROCEDURE\b)/gi)) push("function", f.name, "D", norm(body.slice(m.index!, m.index! + 60)), at(m.index!));
  }

  // RLS policies
  for (const p of (await c.query<{ t: string; n: string; q: string | null; w: string | null }>(`SELECT tablename AS t, policyname AS n, qual AS q, with_check AS w FROM pg_policies WHERE schemaname = 'kauro' ORDER BY 1, 2`)).rows) {
    const text = `${p.q ?? ""} ; ${p.w ?? ""}`;
    const at = index.objects.get(`policy:${p.t}.${p.n}`) ?? "live-only";
    for (const x of primitivesOf(text)) push("policy", `${p.t}.${p.n}`, "P", x.text, at);
    for (const j of judgesOf(text, vocab)) push("policy", `${p.t}.${p.n}`, "J", j.text, at, { operands: j.operands });
  }

  // CHECK constraints
  for (const k of (await c.query<{ t: string; n: string; d: string }>(
    `SELECT r.relname AS t, k.conname AS n, pg_get_constraintdef(k.oid) AS d FROM pg_constraint k JOIN pg_class r ON r.oid = k.conrelid JOIN pg_namespace s ON s.oid = r.relnamespace
      WHERE s.nspname = 'kauro' AND k.contype = 'c' ORDER BY 1, 2`,
  )).rows) {
    const at = index.objects.get(`check:${k.n}`) ?? index.objects.get(`column:${k.t}.${k.n.replace(new RegExp(`^${k.t}_`), "").replace(/_check\d*$/, "")}`) ?? `table:${k.t}`;
    for (const x of primitivesOf(k.d)) push("check", `${k.t}.${k.n}`, "P", x.text, at);
    for (const j of judgesOf(k.d, vocab)) push("check", `${k.t}.${k.n}`, "J", j.text, at, { operands: j.operands });
  }

  // views
  for (const v of (await c.query<{ n: string; d: string }>(`SELECT viewname AS n, definition AS d FROM pg_views WHERE schemaname = 'kauro' ORDER BY 1`)).rows) {
    const at = index.objects.get(`view:${v.n}`) ?? "live-only";
    for (const x of primitivesOf(v.d)) push("view", v.n, "P", x.text, at);
    for (const j of judgesOf(v.d, vocab)) push("view", v.n, "J", j.text, at, { operands: j.operands });
  }

  // triggers: WHEN clauses, require_server_instant arguments, and the deferred ones (CK1 AT_COMMIT checks, CK2)
  const triggers = (await c.query<{ t: string; n: string; d: string; fn: string; deferrable: boolean; body: string }>(
    `SELECT r.relname AS t, g.tgname AS n, pg_get_triggerdef(g.oid) AS d, p.proname AS fn, g.tgdeferrable AS deferrable, p.prosrc AS body
       FROM pg_trigger g JOIN pg_class r ON r.oid = g.tgrelid JOIN pg_namespace s ON s.oid = r.relnamespace JOIN pg_proc p ON p.oid = g.tgfoid
      WHERE s.nspname = 'kauro' AND NOT g.tgisinternal ORDER BY 1, 2`,
  )).rows;
  for (const g of triggers) {
    const at = index.objects.get(`trigger:${g.t}.${g.n}`) ?? "live-only";
    const when = /\bWHEN\s*\(([\s\S]*)\)\s+EXECUTE\s+FUNCTION/i.exec(g.d)?.[1];
    if (when !== undefined) {
      for (const x of primitivesOf(when)) push("trigger_when", `${g.t}.${g.n}`, "P", x.text, at);
      for (const j of judgesOf(when, vocab)) push("trigger_when", `${g.t}.${g.n}`, "J", j.text, at, { operands: j.operands });
    }
    if (g.fn === "require_server_instant") {
      for (const a of /EXECUTE FUNCTION\s+kauro\.require_server_instant\(([^)]*)\)/i.exec(g.d)?.[1]?.match(/'[^']*'/g) ?? []) push("trigger_arg", `${g.t}.${g.n}`, "S", `require_server_instant(${a})`, at, { column: `${g.t}.${a.replace(/'/g, "")}` });
    }
  }

  // column defaults
  for (const d of (await c.query<{ t: string; col: string; e: string }>(
    `SELECT r.relname AS t, a.attname AS col, pg_get_expr(ad.adbin, ad.adrelid) AS e FROM pg_attrdef ad JOIN pg_class r ON r.oid = ad.adrelid JOIN pg_namespace s ON s.oid = r.relnamespace
       JOIN pg_attribute a ON a.attrelid = ad.adrelid AND a.attnum = ad.adnum WHERE s.nspname = 'kauro' ORDER BY 1, 2`,
  )).rows) {
    const at = index.objects.get(`column:${d.t}.${d.col}`) ?? `table:${d.t}`;
    for (const x of primitivesOf(d.e)) push("default", `${d.t}.${d.col}`, "P", x.text, at);
    if (hasClock(d.e, NO_SCOPE)) push("default", `${d.t}.${d.col}`, "S", norm(`DEFAULT ${d.e}`), at, { column: `${d.t}.${d.col}` });
  }

  // every migration file: its primitives wherever they stand (a live body, a replaced body, one-time DML)
  for (const { file, raw } of index.files) {
    for (const p of primitivesOf(raw)) {
      const before = stripComments(raw).slice(0, p.index);
      const fnm = [...before.matchAll(/CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+kauro\.(\w+)/gi)].pop();
      let inBody: string | null = null;
      if (fnm !== undefined) {
        const tagAt = /\bAS\s+(\$\w*\$)/i.exec(before.slice(fnm.index!));
        if (tagAt !== null) {
          const open = fnm.index! + tagAt.index + tagAt[0].length;
          const close = raw.indexOf(tagAt[1]!, open);
          if (close === -1 || close > p.index) inBody = fnm[1]!.toLowerCase();
        }
      }
      if (inBody !== null && SANCTIONED_FUNCTIONS.has(inBody)) continue;
      push("file", file, "P", inBody === null ? p.text : `${p.text} in ${inBody}`, `${file.slice(0, 4)}:${lineAt(raw, p.index)}`);
    }
  }

  const deferredTriggers = triggers.filter((g) => g.deferrable).map((g) => ({ table: g.t, trigger: g.n, fn: g.fn, body: g.body }));
  const deferredForeignKeys = (await c.query<{ name: string; table: string; references: string }>(
    `SELECT k.conname AS name, r.relname AS table, f.relname AS references FROM pg_constraint k JOIN pg_class r ON r.oid = k.conrelid JOIN pg_class f ON f.oid = k.confrelid
       JOIN pg_namespace s ON s.oid = r.relnamespace WHERE s.nspname = 'kauro' AND k.contype = 'f' AND k.condeferrable ORDER BY 2, 1`,
  )).rows;
  return { sites, deferredTriggers, deferredForeignKeys };
}

/** The live function bodies that call `kauro.<fn>(` (a PARAM row's SQL callers). */
export async function sqlCallers(c: Client, fn: string): Promise<string[]> {
  const r = await c.query<{ n: string }>(
    `SELECT DISTINCT p.proname AS n FROM pg_proc p JOIN pg_namespace s ON s.oid = p.pronamespace WHERE s.nspname = 'kauro' AND p.prosrc ~ $1 AND p.proname <> $2 ORDER BY 1`,
    [`kauro\\.${fn}\\s*\\(`, fn],
  );
  return r.rows.map((x) => x.n);
}
