// Writes world.json beside this file: the canonical world, its stress variants, the figures and alerts computed from it, and its
// reconciliation, for readers that cannot load TypeScript (the document pipeline, a PDF renderer). Node 24 runs the module's .ts files
// with its built-in type stripping, so no build step and no dependency is needed:
//
//   node tools/review/private/lib/canon/export.mjs          writes world.json
//   node tools/review/private/lib/canon/export.mjs --check  fails when world.json is out of date
//
// tools/test/canon.test.mjs holds world.json equal to a fresh export, so the file can never drift from the module.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const WORLD_JSON = join(import.meta.dirname, "world.json");

/** The exported document, as a string (stable key order, two-space indent, a final newline). */
export async function exportText() {
  const canon = await import("./index.ts");
  const { reconcile } = await import("./reconcile.ts");
  const world = canon.CANON;
  const payload = {
    about: "Kauro's canonical synthetic world (Order 11 round 3, master plan §2.1). Generated by export.mjs from the TypeScript module; do not edit.",
    asOf: world.asOf,
    world,
    figures: {
      kauro: canon.kauroFigures(world),
      sellers: Object.fromEntries(world.sellers.map((seller) => [seller.id, canon.sellerFigures(world, seller.id)])),
    },
    alerts: canon.computeAlerts(world),
    reconciliation: reconcile(world),
    // the 200-row list is generated from its index alone (stress.ts LIST_200); written out it would be two thirds of this file, so only its
    // shape is exported and a reader that needs the rows loads the module (Node 24 runs it as is)
    stress: Object.fromEntries(
      Object.entries(canon.STRESS_WORLDS).map(([key, one]) => [
        key,
        key === "list200"
          ? { summary: { source: "stress.ts LIST_200", workspaces: one.workspaces.length, clients: one.clients.length, projects: one.projects.length, firstProject: one.projects[0], lastProject: one.projects.at(-1) }, reconciliation: reconcile(one) }
          : { world: one, reconciliation: reconcile(one) },
      ]),
    ),
  };
  return `${JSON.stringify(payload, null, 2)}\n`;
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await exportText();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(WORLD_JSON, "utf8");
    } catch {
      current = "";
    }
    if (current !== text) {
      process.stderr.write("world.json is out of date: run node tools/review/private/lib/canon/export.mjs\n");
      process.exit(1);
    }
    process.stdout.write("world.json is current\n");
  } else {
    writeFileSync(WORLD_JSON, text);
    process.stdout.write(`wrote ${WORLD_JSON} (${text.length} characters)\n`);
  }
}
