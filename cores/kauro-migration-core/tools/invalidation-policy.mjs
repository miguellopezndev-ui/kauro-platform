/**
 * Which changes to the tree invalidate which evidence.
 *
 * Every qualification result in this repository — a vendor gate, a capacity
 * measurement, the offline universe — is a statement about an execution
 * subject: the runtime that ran, the harness that drove it, the oracle it was
 * judged against, the fixtures it was fed, the contracts it honoured, the
 * dependencies it linked and the workflow that will re-run it. A change to any
 * of those changes what the evidence is evidence about. A change to a README
 * does not.
 *
 * That distinction used to live in people's heads, and it failed in both
 * directions: evidence was re-stamped onto new code as if a stamp were a
 * measurement (MC-2 item 1), and a wording correction in a document was treated
 * as a reason to repeat a two-hour campaign. So it is a function now, and it is
 * tested: `classifyPath` says which class a tracked path belongs to, and the
 * execution subject (`tools/execution-subject.mjs`) is the digest of every path
 * that is not EDITORIAL, GENERATED or EVIDENCE.
 *
 * The classes, in the order the rules are tried:
 *
 *   WORKFLOW           .github/**            re-run CI; the campaign stands
 *   EVIDENCE           qualification outputs  produced by a campaign, never an input to one
 *   GENERATED          acceptance/**          regenerated by the universe from the code
 *   SEMANTIC_ORACLE    expected truths, corpora, capacity profiles, fixtures, the allowlist of instances
 *   SEMANTIC_CONTRACT  src/adapters, src/target, src/profile, src/domain, spec/
 *   SEMANTIC_RUNTIME   the rest of src/, package.json, the lockfile, tsconfig
 *   SEMANTIC_HARNESS   tools/, qualification runners and the launcher, test code
 *   EDITORIAL          everything else: README, docs, qualification READMEs, notes
 *
 * Anything SEMANTIC_* or WORKFLOW is part of the subject. EDITORIAL is not, and
 * that is the whole guarantee: correcting prose cannot move the subject digest,
 * and moving a runner, an oracle, a mapper, a contract or the engine cannot
 * leave it still.
 */

export const CHANGE_CLASSES = Object.freeze([
  'WORKFLOW',
  'EVIDENCE',
  'GENERATED',
  'SEMANTIC_ORACLE',
  'SEMANTIC_CONTRACT',
  'SEMANTIC_RUNTIME',
  'SEMANTIC_HARNESS',
  'EDITORIAL',
]);

/** The classes whose files make up the execution subject. */
export const SUBJECT_CLASSES = Object.freeze(['WORKFLOW', 'SEMANTIC_ORACLE', 'SEMANTIC_CONTRACT', 'SEMANTIC_RUNTIME', 'SEMANTIC_HARNESS']);

/** The classes a change in which requires a new campaign (vendor gates and capacity) and a new universe. */
export const REQUALIFYING_CLASSES = Object.freeze(['SEMANTIC_ORACLE', 'SEMANTIC_CONTRACT', 'SEMANTIC_RUNTIME', 'SEMANTIC_HARNESS']);

const EVIDENCE_PATTERNS = [
  /^qualification\/evidence\/.+\.json$/u,
  /^qualification\/capacity\/(?!profiles\.json$).+\.json$/u,
  /^qualification\/candidate\/.+$/u,
  // The release provenance record. Named for the file the tree writes, which is
  // `migration-core-provenance.json` — this pattern still carried the v1 name the
  // record had before it was renamed, so `classifyPath` fell through every
  // pattern and returned EDITORIAL. A regenerated release provenance therefore
  // reported `editorialOnly: true`: "the campaign stands", about the document
  // that describes the campaign. drift-gate.mjs handled the same rename
  // correctly, so the two tools disagreed about one filename.
  /^migration-core-provenance\.json$/u,
];

const ORACLE_PATTERNS = [
  /^qualification\/[^/]+\/EXPECTED_TRUTH\.md$/u,
  /^qualification\/[^/]+\/oracle\.json$/u,
  /^qualification\/[^/]+\/corpus\//u,
  /^qualification\/capacity\/profiles\.json$/u,
  /^qualification\/authorized-instances\.json$/u,
  /^test\/fixtures\//u,
  /^docs\/work\/DOCUMENT_LIFECYCLE\.json$/u,
];

const CONTRACT_PATTERNS = [/^src\/adapters\//u, /^src\/target\//u, /^src\/profile\//u, /^src\/domain\//u, /^spec\//u];

const RUNTIME_PATTERNS = [/^src\//u, /^package\.json$/u, /^package-lock\.json$/u, /^tsconfig\.json$/u];

const HARNESS_PATTERNS = [
  /^tools\//u,
  // Everything under qualification/ that is not evidence and not an oracle.
  //
  // This was `qualification\/[^/]+\/.+\.(mjs|js|ts|java)`, which requires a
  // subdirectory — so every module sitting directly under qualification/ fell
  // through every pattern and classified as EDITORIAL, which is not in the
  // subject at all. That is qualification/oracles.mjs, which *is* the oracle
  // the release gate checks all five vendor evidence files against;
  // qualification/campaign.mjs, which is captureStart, captureEnd and
  // assertInstanceAuthorised; and qualification/namespace.mjs, which is the
  // tenant cleanup ledger. Deleting a required case from the oracle, or making
  // the instance allowlist a no-op, moved nothing: the subject digest held, the
  // sealed campaign still matched, and every measurement taken before the
  // weakening stayed accepted. It is the exact defect this module's header says
  // it exists to prevent — "a runner could change what it expected without the
  // binding moving".
  // Everything but the prose. A qualification README documents the contract
  // with the auth directory and is worth reading; it is not what a runner
  // does, and an editorial correction to one should not invalidate a
  // campaign. EXPECTED_TRUTH.md is matched as an oracle above and never
  // reaches here.
  /^qualification\/(?!.*\.md$)/u,
  /^test\//u,
  // The repository root's own configuration. .gitattributes is `* -text`, and
  // its comment says any end-of-line translation would silently break the
  // cross-platform determinism proof; deleting it was an editorial change.
  /^\.gitattributes$/u,
  /^\.npmrc$/u,
  /^\.nvmrc$/u,
  // Launchers. bench/prepare-universe.sh regenerates the records the universe
  // checks and bench/campaign.sh decides which capacity legs run and in what
  // order; both were EDITORIAL, so a launcher that swallowed a failed gate
  // moved nothing. An executable path outside src/ and tools/ is still an
  // executable path.
  /^bench\/.+\.(sh|mjs|cjs|js|ps1)$/u,
];

function matches(patterns, path) {
  return patterns.some((pattern) => pattern.test(path));
}

/**
 * The class of one repository-relative POSIX path.
 *
 * @param {string} path repository-relative, `/`-separated
 * @returns {string} one of CHANGE_CLASSES
 */
export function classifyPath(path) {
  if (typeof path !== 'string' || path === '' || path.includes('\\')) {
    throw new Error(`classifyPath expects a repository-relative POSIX path, got ${String(path)}`);
  }
  if (path.startsWith('.github/')) return 'WORKFLOW';
  if (matches(EVIDENCE_PATTERNS, path)) return 'EVIDENCE';
  if (path.startsWith('acceptance/')) return 'GENERATED';
  if (matches(ORACLE_PATTERNS, path)) return 'SEMANTIC_ORACLE';
  if (matches(CONTRACT_PATTERNS, path)) return 'SEMANTIC_CONTRACT';
  if (matches(RUNTIME_PATTERNS, path)) return 'SEMANTIC_RUNTIME';
  if (matches(HARNESS_PATTERNS, path)) return 'SEMANTIC_HARNESS';
  return 'EDITORIAL';
}

/**
 * What a set of changed paths does to the evidence.
 *
 * @param {readonly string[]} paths
 * @returns {{classes: Record<string, string[]>, subjectMoved: boolean, requalify: boolean, workflowMoved: boolean, editorialOnly: boolean}}
 */
export function consequenceOf(paths) {
  const classes = Object.fromEntries(CHANGE_CLASSES.map((name) => [name, []]));
  for (const path of paths) classes[classifyPath(path)].push(path);
  const subjectMoved = SUBJECT_CLASSES.some((name) => classes[name].length > 0);
  const requalify = REQUALIFYING_CLASSES.some((name) => classes[name].length > 0);
  return {
    classes,
    subjectMoved,
    requalify,
    workflowMoved: classes.WORKFLOW.length > 0,
    editorialOnly: paths.length > 0 && !subjectMoved && classes.EVIDENCE.length === 0 && classes.GENERATED.length === 0,
  };
}
