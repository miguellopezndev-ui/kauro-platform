// Refreshes deploy/aws/cost/prices.json from AWS's public Price List bulk API (no account, no credential, no charge). Every price
// in the estimate comes from here: the item's SKU, its OnDemand rate, the offer's publication date and the SHA-256 of the offer
// file read, so anyone can re-download the same file and check it.
//
//   node deploy/aws/cost/refresh-prices.mjs                 download the offers into a temporary folder, then extract
//   node deploy/aws/cost/refresh-prices.mjs --from <dir>    extract from offer files already downloaded (<offer>.json)
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const HERE = import.meta.dirname;
const catalog = JSON.parse(readFileSync(join(HERE, "catalog.json"), "utf8"));
const offerUrl = (offer) => `https://pricing.us-east-1.amazonaws.com/offers/v1.0/aws/${offer}/current/${catalog.region}/index.json`;

const fromIndex = process.argv.indexOf("--from");
const fromDir = fromIndex > 0 ? process.argv[fromIndex + 1] : null;
const workDir = fromDir ?? mkdtempSync(join(tmpdir(), "kauro-aws-prices-"));

async function offerFile(offer) {
  const path = join(workDir, `${offer}.json`);
  if (!fromDir) {
    const response = await fetch(offerUrl(offer));
    if (!response.ok) throw new Error(`${offer}: HTTP ${response.status}`);
    writeFileSync(path, Buffer.from(await response.arrayBuffer()));
  }
  const bytes = readFileSync(path);
  return { bytes, json: JSON.parse(bytes.toString("utf8")) };
}

function find(item, offer) {
  const matches = [];
  for (const [sku, product] of Object.entries(offer.products)) {
    const attributes = product.attributes ?? {};
    if (attributes.usagetype !== item.usagetype) continue;
    if (attributes.regionCode && attributes.regionCode !== catalog.region) continue;
    if (item.attributes && !Object.entries(item.attributes).every(([k, v]) => attributes[k] === v)) continue;
    for (const term of Object.values(offer.terms.OnDemand[sku] ?? {})) {
      for (const dimension of Object.values(term.priceDimensions)) {
        if (item.beginRange !== undefined && dimension.beginRange !== item.beginRange) continue;
        matches.push({ sku, usd: dimension.pricePerUnit.USD, unit: dimension.unit, beginRange: dimension.beginRange, endRange: dimension.endRange, description: dimension.description });
      }
    }
  }
  const distinct = [...new Map(matches.map((m) => [`${m.usd}|${m.beginRange}`, m])).values()];
  if (distinct.length !== 1) throw new Error(`${item.id}: ${distinct.length} distinct prices match ${JSON.stringify(item)} (narrow the catalog entry)`);
  return distinct[0];
}

const offers = {};
const items = {};
try {
  for (const item of catalog.items) {
    offers[item.offer] ??= await offerFile(item.offer);
    const match = find(item, offers[item.offer].json);
    items[item.id] = { usd: Number(match.usd), unit: item.unit, priceListUnit: match.unit, sku: match.sku, offer: item.offer, usagetype: item.usagetype, description: match.description };
  }
} finally {
  if (!fromDir) rmSync(workDir, { recursive: true, force: true });
}

const out = {
  $comment: "Generated by deploy/aws/cost/refresh-prices.mjs from AWS's Price List bulk API. Do not edit by hand.",
  region: catalog.region,
  offers: Object.fromEntries(
    Object.entries(offers).sort(([a], [b]) => a.localeCompare(b)).map(([offer, { bytes, json }]) => [
      offer,
      { url: offerUrl(offer), publicationDate: json.publicationDate, version: json.version, sha256: createHash("sha256").update(bytes).digest("hex") },
    ]),
  ),
  items: Object.fromEntries(Object.entries(items).sort(([a], [b]) => a.localeCompare(b))),
  pageStatements: catalog.pageStatements,
};
writeFileSync(join(HERE, "prices.json"), `${JSON.stringify(out, null, 2)}\n`);
console.log(`prices.json: ${Object.keys(items).length} prices from ${Object.keys(offers).length} offers`);
